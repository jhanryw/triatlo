#!/bin/sh
# Generates ALL Supabase secrets locally with the official upstream scripts (utils/generate-keys.sh and
# utils/add-new-auth-keys.sh) and writes the resulting .env OUTSIDE the repository.
#
#   sh infra/supabase/scripts/prepare-env.sh                       # create secrets (refuses to overwrite)
#   sh infra/supabase/scripts/prepare-env.sh --api-url https://A --app-url https://B   # also fill the URLs
#   sh infra/supabase/scripts/prepare-env.sh --urls-only --api-url https://A --app-url https://B   # only update URLs
#   sh infra/supabase/scripts/prepare-env.sh --status              # report which keys are set (never prints values)
#   options: --out FILE (default ~/.triatlo-secrets/supabase.env)   --force (overwrite an existing file)
#
# No secret value is ever printed. Requires: openssl, node >= 16 (or docker), sed.
set -eu
umask 077   # every file this script writes (including the --urls-only rewrite) stays private

HERE="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${HOME}/.triatlo-secrets/supabase.env"
FORCE=0; URLS_ONLY=0; STATUS=0; API_URL=""; APP_URL=""

while [ $# -gt 0 ]; do
  case "$1" in
    --out) OUT="$2"; shift 2 ;;
    --force) FORCE=1; shift ;;
    --urls-only) URLS_ONLY=1; shift ;;
    --status) STATUS=1; shift ;;
    --api-url) API_URL="${2%/}"; shift 2 ;;
    --app-url) APP_URL="${2%/}"; shift 2 ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

REQUIRED_SECRETS="POSTGRES_PASSWORD JWT_SECRET ANON_KEY SERVICE_ROLE_KEY SUPABASE_PUBLISHABLE_KEY SUPABASE_SECRET_KEY JWT_KEYS JWT_JWKS ANON_KEY_ASYMMETRIC SERVICE_ROLE_KEY_ASYMMETRIC SECRET_KEY_BASE REALTIME_DB_ENC_KEY VAULT_ENC_KEY PG_META_CRYPTO_KEY LOGFLARE_PUBLIC_ACCESS_TOKEN LOGFLARE_PRIVATE_ACCESS_TOKEN S3_PROTOCOL_ACCESS_KEY_ID S3_PROTOCOL_ACCESS_KEY_SECRET MINIO_ROOT_PASSWORD DASHBOARD_PASSWORD"

value_of() { grep "^$1=" "$2" | head -n1 | cut -d= -f2- | tr -d '\r'; }

report() {
  file="$1"; bad=0
  echo "Secrets in $file (values are never shown):"
  for k in $REQUIRED_SECRETS; do
    v="$(value_of "$k" "$file")"
    if [ -z "$v" ]; then echo "  MISSING  $k"; bad=1
    else echo "  set      $k (${#v} chars)"; fi
  done
  for k in SUPABASE_PUBLIC_URL API_EXTERNAL_URL SITE_URL; do
    v="$(value_of "$k" "$file")"
    case "$v" in
      ""|*REPLACE_WITH*) echo "  TODO     $k (fill with the HTTPS address generated by EasyPanel)"; bad=2 ;;
      https://*) echo "  set      $k" ;;
      *) echo "  WARNING  $k is not an https:// URL"; bad=1 ;;
    esac
  done
  # Defaults that must never reach production
  for pair in "DISABLE_SIGNUP=true" "ENABLE_PHONE_SIGNUP=false" "ENABLE_ANONYMOUS_USERS=false" "ENABLE_EMAIL_AUTOCONFIRM=false"; do
    k="${pair%%=*}"; want="${pair#*=}"; v="$(value_of "$k" "$file")"
    if [ "$v" = "$want" ]; then echo "  ok       $k=$want"; else echo "  WARNING  $k should be $want"; bad=1; fi
  done
  dp="$(value_of DASHBOARD_PASSWORD "$file")"
  case "$dp" in *[A-Za-z]*) ;; *) echo "  WARNING  DASHBOARD_PASSWORD must contain at least one letter"; bad=1 ;; esac
  return $bad
}

set_url() { # key value file
  tmp="$3.tmp"; sed "s|^$1=.*|$1=$2|" "$3" > "$tmp" && mv "$tmp" "$3"
}

apply_urls() {
  file="$1"
  if [ -n "$API_URL" ]; then
    case "$API_URL" in https://*) ;; *) echo "--api-url must start with https://" >&2; exit 2 ;; esac
    set_url SUPABASE_PUBLIC_URL "$API_URL" "$file"
    set_url API_EXTERNAL_URL "$API_URL/auth/v1" "$file"
  fi
  if [ -n "$APP_URL" ]; then
    case "$APP_URL" in https://*) ;; *) echo "--app-url must start with https://" >&2; exit 2 ;; esac
    set_url SITE_URL "$APP_URL" "$file"
  fi
}

if [ "$STATUS" = 1 ]; then
  [ -f "$OUT" ] || { echo "no file at $OUT" >&2; exit 1; }
  report "$OUT"; exit $?
fi

if [ "$URLS_ONLY" = 1 ]; then
  [ -f "$OUT" ] || { echo "no file at $OUT (run without --urls-only first)" >&2; exit 1; }
  apply_urls "$OUT"; report "$OUT"; exit $?
fi

if [ -e "$OUT" ] && [ "$FORCE" != 1 ]; then
  echo "refusing to overwrite $OUT (use --force, or --urls-only to just update the URLs)" >&2
  exit 1
fi

umask 077
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT INT TERM
mkdir -p "$WORK/utils"
cp "$HERE/.env.example" "$WORK/.env"
# The upstream key script also edits docker-compose.yml (uncomments the JWKS lines); it works on this throw-away copy.
cp "$HERE/docker-compose.yml" "$WORK/docker-compose.yml"
cp "$HERE/utils/generate-keys.sh" "$HERE/utils/add-new-auth-keys.sh" "$WORK/utils/"

# Official generators; stdout/stderr discarded so no secret reaches the terminal or any log.
( cd "$WORK" && sh utils/generate-keys.sh --update-env >/dev/null 2>&1 ) || { echo "generate-keys.sh failed" >&2; exit 1; }
( cd "$WORK" && sh utils/add-new-auth-keys.sh --update-env >/dev/null 2>&1 ) || { echo "add-new-auth-keys.sh failed (needs node >= 16 or docker)" >&2; exit 1; }
rm -f "$WORK"/.env.old "$WORK"/.env.old.*
# The committed compose must already contain the asymmetric-key configuration (nothing left to uncomment).
if ! cmp -s "$WORK/docker-compose.yml" "$HERE/docker-compose.yml"; then
  echo "docker-compose.yml in the repo is missing the JWKS lines the key script enables; fix it and retry" >&2; exit 1
fi

apply_urls "$WORK/.env"

mkdir -p "$(dirname "$OUT")"; chmod 700 "$(dirname "$OUT")"
cp "$WORK/.env" "$OUT"; chmod 600 "$OUT"
echo "wrote $OUT (mode 600, outside the repository)"
report "$OUT" || true
